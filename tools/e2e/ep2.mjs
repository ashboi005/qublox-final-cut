import puppeteer from 'puppeteer-core';
import { mkdirSync } from 'node:fs';
const BASE = process.env.GAME_URL ?? 'http://localhost:5173';
const out = process.argv[2] ?? 'tools/e2e/shots';
mkdirSync(out, { recursive: true });
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage();
await page.setViewport({ width: 1280, height: 800 });
const logs = []; page.on('console', m => { if (['error', 'warning'].includes(m.type()) && !m.text().includes('GL Driver')) logs.push(m.text()); }); page.on('pageerror', e => logs.push('PAGEERROR ' + e.message));
const wait = ms => new Promise(r => setTimeout(r, ms));
const g = (fn, ...a) => page.evaluate(fn, ...a);
const skip = async () => { for (let i = 0; i < 40 && await g(() => !!document.querySelector('.dialogue')); i++) { await page.keyboard.press('Escape'); await wait(80); } };
const tp = (tx, ty) => g((tx, ty) => { const s = window.__qublox.scene.getScene('game'); s.avatar.setPosition(tx * 16 + 8, (ty + 1) * 16); s.avatar.pbody.setVelocity(0, 0); }, tx, ty);
const room = () => g(() => { const s = window.__qublox.scene.getScene('game'); return `${s.levelKey} [${s.avatar.members.map(m => m.def.id)}]`; });
const press = async k => { await page.keyboard.press(k); await wait(120); };
const swapTo = async id => { const i = await g(id => window.__qublox.scene.getScene('game').avatar.members.findIndex(m => m.def.id === id), id); if (i >= 0) await press(String(i + 1)); };
const ready = () => g(() => { const s = window.__qublox.scene.getScene('game'); for (const m of s.avatar.members) m.abilityReadyAt = 0; });
const toExit = async () => { const e = await g(() => window.__qublox.scene.getScene('game').level.entities.find(e => e.kind === 'X')); await tp(e.tx, e.ty); await wait(900); await skip(); };
const face = d => g(d => { window.__qublox.scene.getScene('game').avatar.facing = d; }, d);
const R = {};
await page.goto(BASE + '/?level=ep2-r01&party=tushar', { waitUntil: 'networkidle0' });
await wait(1800); await press('Escape'); await skip();
R.r01 = await room();
await page.screenshot({ path: `${out}/40-ep2-r01.png` });
await toExit();
R.r02 = await room();
await g(() => { const s = window.__qublox.scene.getScene('game'); for (const e of s.liveEnemies()) e.hit(999, 0); });
await wait(1600); await skip(); await wait(300);
R.r02party = await room();
await swapTo('mansukh'); await tp(37, 13); await face(1); await ready(); await press('k'); await wait(200);
R.penPlatforms = await g(() => window.__qublox.scene.getScene('game').pens.getLength());
await page.screenshot({ path: `${out}/41-ep2-pen.png` });
await toExit();
R.r03 = await room();
await swapTo('manya'); await tp(12, 13); await face(1); await ready(); await press('k'); await wait(400);
R.wallColors = await g(() => [...new Set(window.__qublox.scene.getScene('game').blocks.filter(b => b.tx === 14 || b.tx === 15).map(b => b.color))].join(','));
await tp(25, 13); await ready(); await press('k'); await wait(300); await ready(); await press('k'); await wait(300);
R.bounceBlock = await g(() => window.__qublox.scene.getScene('game').blocks.find(b => b.tx === 27).color);
await g(() => { const s = window.__qublox.scene.getScene('game'); const b = s.blocks.find(b => b.tx === 27); s.avatar.setPosition(b.spr.x, b.spr.y - 30); s.avatar.pbody.setVelocity(0, 50); });
await wait(250);
R.bounceVy = await g(() => Math.round(window.__qublox.scene.getScene('game').avatar.pbody.velocity.y));
await tp(40, 8); await ready(); await press('k'); await wait(300); await ready(); await press('k'); await wait(400);
R.bridge = await g(() => [...new Set(window.__qublox.scene.getScene('game').blocks.filter(b => b.tx >= 41 && b.tx <= 50).map(b => b.color))].join(','));
await page.screenshot({ path: `${out}/42-ep2-blocks.png` });
await toExit();
R.r04 = await room();
await tp(14, 13); await wait(2200);
R.mirrorSpawned = await g(() => window.__qublox.scene.getScene('game').mirrors[0].spawned.length);
await g(() => { const s = window.__qublox.scene.getScene('game'); s.hitMirror(s.mirrors[0], 99); });
R.mirrorHp = await g(() => window.__qublox.scene.getScene('game').mirrors[0].hp <= 0);
await toExit();
R.r05 = await room();
await swapTo('tushar'); await tp(18, 13); await ready(); await press('k'); await wait(200);
R.boomsFrozen = await g(() => { const s = window.__qublox.scene.getScene('game'); return s.booms.filter(b => b.frozenUntil > s.time.now).length + '/' + s.booms.length; });
await page.screenshot({ path: `${out}/43-ep2-booms.png` });
await toExit();
R.r06 = await room();
for (let i = 0; i < 4; i++) { await wait(400); await g(() => { const s = window.__qublox.scene.getScene('game'); for (const e of s.liveEnemies()) e.hit(999, 0); }); await wait(1300); }
R.waveDoor = await g(() => window.__qublox.scene.getScene('game').switches.find(s => s.kind === 'wave').open);
await toExit();
R.r07 = await room();
await skip(); await wait(400); await skip(); await wait(2500);
R.boss = await g(() => { const b = window.__qublox.scene.getScene('game').boss; return `${b.title}:${b.mode}:${Math.round(b.y)}`; });
await g(() => window.__qublox.scene.getScene('game').boss.hit(170, 0)); await wait(200);
R.shield = await g(() => window.__qublox.scene.getScene('game').boss.shielded);
await page.screenshot({ path: `${out}/44-ep2-boss.png` });
await swapTo('ashwath'); await swapTo('manya');
await g(() => { const s = window.__qublox.scene.getScene('game'); s.avatar.setPosition(s.boss.x - 120, s.avatar.y); });
await ready(); await press('k'); await wait(200);
R.shieldAfterPaint = await g(() => window.__qublox.scene.getScene('game').boss.shielded);
await g(() => { const b = window.__qublox.scene.getScene('game').boss; b.dropShield(); b.hit(9999, 0); });
await wait(2600); await skip(); await wait(900);
R.results = await g(() => document.querySelector('.results-stats')?.textContent ?? null);
console.log(JSON.stringify(R, null, 1));
console.log(logs.join('\n') || 'no errors');
await browser.close();
