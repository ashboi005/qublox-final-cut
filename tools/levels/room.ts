// Shared room builder for the level generators. The generated .txt files are what the game reads.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DECOR: Record<string, string[]> = {
  hq: ['decor-water-cooler', 'decor-chai-crate', 'decor-mood-board', 'decor-beanbag'],
  'render-farm': ['decor-server-rack', 'decor-cable-spaghetti', 'decor-warning-sign', 'decor-coolant-drum'],
  'the-set': ['decor-c-stand', 'decor-clapperboard', 'decor-director-chair', 'decor-sandbag'],
  'the-feed': ['decor-ring-light', 'decor-neon-heart', 'decor-phone-tripod', 'decor-trending-arrow'],
  templatr: ['decor-plastic-ficus', 'decor-motivational-poster', 'decor-standing-desk', 'decor-beige-cubicle'],
};

export class Room {
  g: string[][];
  meta: string[] = [];
  constructor(readonly gen: string, readonly key: string, readonly W: number, readonly H = 17) {
    this.g = Array.from({ length: H }, () => Array(W).fill('.'));
    this.fill(0, 0, W - 1, 0, '#');
    this.fill(0, 0, 0, H - 1, '#');
    this.fill(W - 1, 0, W - 1, H - 1, '#');
    this.fill(0, H - 3, W - 1, H - 1, '#');
  }
  set(x: number, y: number, c: string) { if (x >= 0 && x < this.W && y >= 0 && y < this.H) this.g[y]![x] = c; return this; }
  fill(x0: number, y0: number, x1: number, y1: number, c: string) { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) this.set(x, y, c); return this; }
  /** Feet row: the row just above the floor. */
  get floor() { return this.H - 4; }
  m(line: string) { this.meta.push(line); return this; }
  private pinned: string[] = [];
  /** Hand-place one decor prop; the auto-scatter still runs and keeps clear of it. */
  pin(key: string, x: number, y = this.floor) { this.pinned.push(`@decor ${key} ${x} ${y}`); return this; }
  /** Scatter Astra's district decor along the floor (deterministic per room), away from anything interactive. */
  private decorate() {
    const ts = this.meta.find(l => l.startsWith('@tileset '))?.slice(9);
    const keys = DECOR[ts ?? ''];
    if (!keys || this.meta.some(l => l.startsWith('@decor '))) return;
    const f = this.floor;
    const busy = new Set([...this.meta.filter(l => /^@(npc|tape) /.test(l)), ...this.pinned].map(l => Number(l.split(' ')[l.startsWith('@decor') ? 2 : 1])));
    let seed = [...this.key].reduce((a, c) => (a * 31 + c.charCodeAt(0)) >>> 0, 7);
    const rnd = () => ((seed = (seed * 1103515245 + 12345) >>> 0) / 2 ** 32);
    let k = Math.floor(rnd() * keys.length);
    for (let x = 6 + Math.floor(rnd() * 4); x < this.W - 5; x += 8 + Math.floor(rnd() * 6)) {
      let ok = true;
      for (let dx = -2; dx <= 2 && ok; dx++) {
        const c = this.g[f]![x + dx], above = this.g[f - 1]![x + dx], under = this.g[f + 1]![x + dx];
        const free = (ch?: string) => ch === '.' || (ch !== undefined && 'idmbpw'.includes(ch));
        if (!free(c) || !free(above) || under !== '#' || busy.has(x + dx)) ok = false;
      }
      if (!ok) continue;
      this.m(`@decor ${keys[k++ % keys.length]} ${x} ${f}`);
    }
  }
  write() {
    this.decorate();
    this.meta.push(...this.pinned);
    const out = [...this.meta, `; generated by tools/levels/${this.gen}.ts. Legend: see apps/game/src/game/world/level.ts`, ...this.g.map(r => r.join(''))].join('\n') + '\n';
    writeFileSync(join(import.meta.dir, `../../content/levels/${this.key}.txt`), out);
    console.log(`wrote content/levels/${this.key}.txt (${this.W}×${this.H})`);
  }
}
