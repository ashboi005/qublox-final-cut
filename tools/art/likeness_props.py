"""Small crew signature props and couple FX; palette-only native pixels."""
import json
from PIL import Image
from likeness import A, Pen, heart

def draw(name):
    size={'fx-heart':(32,32),'boulder':(16,16),'cracked-wall':(16,32),
          'sprite-can':(16,16),'telescope':(32,32),'decor-trophy':(24,32)}[name]
    im=Image.new('RGBA',size); p=Pen(im)
    if name=='fx-heart':
        heart(p,4,5,2)
        p.l([(6,16),(16,26),(26,16)],21,2)
        p.star(3,3,6,2); p.star(29,26,37,2); p.star(28,4,37,1)
    elif name=='boulder':
        p.p([(1,5),(5,1),(11,0),(14,3),(15,10),(12,14),(5,15),(1,12)],3)
        p.p([(2,5),(6,2),(10,2),(8,6),(3,9)],5,None)
        p.p([(10,5),(13,4),(14,10),(11,13),(6,13),(9,10)],2,None)
        p.l([(8,3),(7,6),(10,8),(9,11)],1)
        p.r((4,10,5,11),4)
    elif name=='cracked-wall':
        p.r((0,0,15,31),3,0)
        for y in range(1,32,8):
            p.l([(1,y),(14,y)],5)
            p.l([(1,y+6),(14,y+6)],2)
            x=4 if y%16==1 else 11
            p.l([(x,y+1),(x,y+5)],2)
        p.l([(8,0),(6,6),(10,11),(5,16),(9,20),(6,26),(8,31)],0,2)
        p.l([(10,11),(13,10),(15,12)],0)
        p.l([(5,16),(2,18),(0,17)],0)
        p.l([(9,20),(12,24),(15,24)],0)
        p.l([(10,2),(9,5),(12,9)],4)
    elif name=='sprite-can':
        p.p([(5,1),(11,1),(12,3),(12,13),(10,15),(5,15),(3,13),(3,3)],0)
        p.r((4,3,11,12),28); p.r((9,3,11,12),27)
        p.r((5,2,10,2),5); p.r((7,1,9,1),3)
        p.l([(4,12),(11,5)],6,2)
        p.p([(5,5),(6,3),(9,4),(8,6),(6,7)],22,None)
        p.r((5,4,5,4),6); p.l([(5,14),(10,14)],5)
    elif name=='telescope':
        p.l([(16,18),(6,30)],0,3); p.l([(17,19),(26,30)],0,3)
        p.l([(17,19),(16,31)],0,3)
        p.l([(16,19),(7,29)],4); p.l([(18,21),(25,29)],3)
        p.l([(17,21),(16,30)],5)
        p.r((14,15,20,19),2,0); p.r((15,16,18,17),23)
        p.p([(6,16),(4,12),(22,3),(26,11),(9,19)],18)
        p.l([(6,12),(22,4)],19,2)
        p.p([(21,3),(25,1),(30,10),(26,12)],0)
        p.l([(24,3),(28,9)],35,2); p.l([(24,3),(25,5)],6)
        p.p([(3,13),(6,12),(8,16),(4,18),(2,16)],2)
        p.l([(10,7),(14,5),(15,7)],0,3)
    else:
        p.r((4,28,20,31),0); p.r((6,24,18,28),2,0)
        p.r((8,25,16,27),23); p.l([(12,25),(12,27)],6)
        p.r((10,17,14,23),23,0); p.l([(11,18),(11,22)],22)
        p.p([(6,4),(18,4),(17,13),(14,17),(10,17),(7,13)],23)
        p.p([(7,5),(12,5),(12,14),(10,14),(8,11)],22,None)
        p.l([(6,6),(2,6),(2,11),(8,14)],22,2)
        p.l([(18,6),(22,6),(22,11),(16,14)],23,2)
        p.p([(7,23),(17,23),(19,25),(5,25)],22)
        p.r((6,3,18,5),22,0); p.l([(7,4),(16,4)],6)
        p.star(18,1,6,1)
    return im

if __name__=='__main__':
    path=A/'manifest.json'; m=json.loads(path.read_text())
    for name in ('fx-heart','boulder','cracked-wall','sprite-can','telescope','decor-trophy'):
        im=draw(name)
        file=f'fx/heart.png' if name=='fx-heart' else f'sprites/props/{name}.png'
        im.save(A/file)
        m['images'][name]={'file':file}
    path.write_text(json.dumps(m,indent=2)+'\n')
